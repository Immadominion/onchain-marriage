const CONTRACT_ADDRESS = "0xd9145CCE52D386f254917e481eB44e9943F39138";

const MarriageCertificateDapp = () => {
  const [partnerAddress, setPartnerAddress] = useState("");
  const [isLoading, setIsLoading] = useState(false);
  const { login, user, authenticated } = usePrivy();

  const publicClient = createPublicClient({
    chain: base,
    transport: http(),
  });

  const mintCertificate = async () => {
    if (!user?.wallet?.address || !partnerAddress) return;

    try {
      setIsLoading(true);

      // Create wallet client
      const walletClient = createWalletClient({
        chain: base,
        transport: custom(window.ethereum),
      });

      // Prepare the transaction
      const data = encodeFunctionData({
        abi: CONTRACT_ABI,
        functionName: "mintMarriageCertificate",
        args: [partnerAddress],
      });

      // Send transaction
      const hash = await walletClient.sendTransaction({
        account: user.wallet.address as `0x${string}`,
        to: CONTRACT_ADDRESS,
        data,
      });

      // Wait for transaction
      // const _receipt = await publicClient.waitForTransactionReceipt({ hash });
      await publicClient.waitForTransactionReceipt({ hash });
      

      alert(
        "Marriage Certificate NFT minted successfully! 💍\nTransaction: " + hash
      );
    } catch (error) {
      console.error("Error minting certificate:", error);
      alert("Failed to mint Marriage Certificate. Please try again.");
    } finally {
      setIsLoading(false);
    }
  };

  return (
    <div className="app-container">
      <nav className="navbar">
        <div className="nav-content">
          <div className="logo">
            <Heart color="#ec4899" size={24} />
            <span>Eternal Bond</span>
          </div>
          {authenticated ? (
            <div className="wallet-info">
              <span>
                Connected: {user?.wallet?.address?.slice(0, 6)}...
                {user?.wallet?.address?.slice(-4)}
              </span>
            </div>
          ) : (
            <button onClick={() => login()} className="connect-button">
              <Wallet size={18} />
              Connect Wallet
            </button>
          )}
        </div>
      </nav>

      <main className="main-content">
        <div className="container">
          <div className="hero-section">
            <h1>Eternalize Your Love On-Chain</h1>
            <p>
              Mint your marriage certificate on Base network and make your
              commitment eternal
            </p>
          </div>

          <div className="certificate-form">
            <div className="form-header">
              <Diamond className="diamond-icon" size={32} />
              <h2>Create Marriage Certificate</h2>
            </div>

            <div className="form-content">
              <div className="input-group">
                <label>Partner's Wallet Address</label>
                <input
                  type="text"
                  value={partnerAddress}
                  onChange={(e) => setPartnerAddress(e.target.value)}
                  placeholder="Enter your partner's Base wallet address"
                />
              </div>

              <button
                className="mint-button"
                disabled={!authenticated || !partnerAddress || isLoading}
                onClick={mintCertificate}
              >
                <Scroll size={20} />
                {isLoading ? "Minting..." : "Mint Marriage Certificate"}
              </button>
            </div>
          </div>
        </div>
      </main>
    </div>
  );
};

export default MarriageCertificateDapp;


